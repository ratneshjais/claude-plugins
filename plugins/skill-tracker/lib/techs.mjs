/** Look up a package name in a map that may contain vendor prefixes ending in "/". */
export function lookup(map, name) {
  if (Object.hasOwn(map, name)) return map[name];
  for (const [key, value] of Object.entries(map)) {
    if (key.endsWith("/") && name.startsWith(key)) return value;
  }
  return null;
}
